def write_csv(path: Path, rows: list[dict], columns: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(columns)
        for r in rows:
            w.writerow([_fmt(r[c]) for c in columns])


def _fmt(v):
    if isinstance(v, date):
        return v.isoformat()
    if isinstance(v, bool):
        return "true" if v else "false"
    return "" if v is None else v


def generate(raw_dir: Path = RAW_DIR, assumptions_path: Path | None = ASSUMPTIONS_PATH) -> dict:
    rng = random.Random(SEED)
    sim = simulate(rng)
    customers, subs, events = sim["customers"], sim["subs"], sim["events"]

    write_csv(raw_dir / "customers.csv", customers,
              ["customer_key", "partner_id", "customer_ref", "channel"])

    register_rows = [{
        "subscription_key": s.key, "customer_key": s.customer_key,
        "term_type": s.term_type, "opened_date": s.opened,
        "register_quantity": s.register_qty, "register_status": s.status,
        "register_status_date": s.status_date,
    } for s in subs]
    write_csv(raw_dir / "subscriptions_register.csv", register_rows,
              ["subscription_key", "customer_key", "term_type", "opened_date",
               "register_quantity", "register_status", "register_status_date"])

    write_csv(raw_dir / "order_events.csv", events,
              ["transaction_id", "received_date", "subscription_key", "transaction_type",
               "requested_quantity", "term_type", "source"])

    # --- counts for the manifest and the assumptions document ------------------------
    by_type = {}
    for e in events:
        by_type[e["transaction_type"]] = by_type.get(e["transaction_type"], 0) + 1
    by_type = dict(sorted(by_type.items()))
    n_annual = sum(1 for s in subs if s.term_type == "annual")
    n_cancelled = sum(1 for s in subs if s.status == "cancelled")
    asm = sim["active_sub_months"]
    intended = sim["intended_rejects"]
    n_rejects_intended = sum(intended.values())
    refs = {}
    for c in customers:
        refs[c["customer_ref"]] = refs.get(c["customer_ref"], 0) + 1
    refs_colliding = sum(1 for v in refs.values() if v > 1)

    parameters = {
        "SEED": SEED, "AS_OF": AS_OF.isoformat(),
        "WINDOW_START": WINDOW_START.isoformat(), "WINDOW_END": WINDOW_END.isoformat(),
        "N_CUSTOMERS": N_CUSTOMERS, "N_DIRECT": N_DIRECT,
        "PARTNERS": [{"partner_id": p, "partner_name": n, "share": s} for p, n, s in PARTNERS],
        "P_ANNUAL": P_ANNUAL, "P_SECOND_SUBSCRIPTION": P_SECOND_SUBSCRIPTION,
        "PARTNER_QTY": {"median": PARTNER_QTY_MEDIAN, "sigma": PARTNER_QTY_SIGMA, "range": PARTNER_QTY_RANGE},
        "DIRECT_QTY": {"median": DIRECT_QTY_MEDIAN, "sigma": DIRECT_QTY_SIGMA, "range": DIRECT_QTY_RANGE},
        "P_ADD": P_ADD, "P_REDUCE": P_REDUCE, "P_CANCEL": P_CANCEL, "P_REJECT": P_REJECT,
        "ADD_UPLIFT": ADD_UPLIFT, "REDUCE_FACTOR": REDUCE_FACTOR,
        "REJECT_MIX_ACTIVE": dict(REJECT_MIX_ACTIVE), "REJECT_MIX_CANCELLED": dict(REJECT_MIX_CANCELLED),
        "AFTER_CANCEL_MONTHS": AFTER_CANCEL_MONTHS, "UNKNOWN_KEY_BASE": UNKNOWN_KEY_BASE,
    }
    realised = {
        "active_subscription_months": asm,
        "rate_per_active_subscription_month": {
            "ADD": by_type.get("ADD", 0) - intended.get("NOOP_QUANTITY", 0) - intended.get("ADD_AFTER_CANCEL", 0)
                   - sum(1 for e in events if e["transaction_type"] == "ADD" and e["subscription_key"] not in {s.key for s in subs}),
            "REDUCE": by_type.get("REDUCE", 0) - intended.get("REDUCE_TO_ZERO", 0) - intended.get("REDUCE_AFTER_CANCEL", 0)
                      - sum(1 for e in events if e["transaction_type"] == "REDUCE" and e["subscription_key"] not in {s.key for s in subs}),
            "CANCEL": by_type.get("CANCEL", 0) - intended.get("DUPLICATE_CANCEL", 0),
            "REJECT": n_rejects_intended,
        },
    }
    for k in list(realised["rate_per_active_subscription_month"]):
        n = realised["rate_per_active_subscription_month"][k]
        realised["rate_per_active_subscription_month"][k] = {"count": n, "rate": round(n / asm, 5) if asm else None}

    manifest = {
        "module": "cascadia-revenue-assurance",
        "generator": "src/generate.py",
        "generator_version": GENERATOR_VERSION,
        "disclosure": DISCLOSURE,
        "seed": SEED,
        "as_of_date": AS_OF.isoformat(),
        "window": {"start": WINDOW_START.isoformat(), "end": WINDOW_END.isoformat()},
        "parameters": parameters,
        "counts": {
            "customers": len(customers),
            "customers_by_partner": {**sim["partner_counts"], DIRECT_ID: N_DIRECT},
            "customer_refs_shared_across_partners": refs_colliding,
            "subscriptions": len(subs),
            "subscriptions_annual": n_annual,
            "subscriptions_monthly": len(subs) - n_annual,
            "subscriptions_cancelled_by_as_of": n_cancelled,
            "transactions": len(events),
            "transactions_by_type": by_type,
            "transactions_intended_to_be_refused_by_reason": intended,
        },
        "realised_movement": realised,
        "files": ["customers.csv", "subscriptions_register.csv", "order_events.csv", "manifest.json"],
    }
    (raw_dir / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=False) + "\n",
                                           encoding="utf-8", newline="\n")

    if assumptions_path is not None:
        assumptions_path.parent.mkdir(parents=True, exist_ok=True)
        assumptions_path.write_text(render_assumptions(manifest), encoding="utf-8", newline="\n")
    return manifest


