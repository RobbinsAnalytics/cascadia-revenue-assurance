class Sub:
    __slots__ = ("key", "customer_key", "partner_id", "channel", "term_type",
                 "opened", "register_qty", "status", "status_date", "cancel_month")

    def __init__(self, key, customer_key, partner_id, channel, term_type, opened, qty):
        self.key = key
        self.customer_key = customer_key
        self.partner_id = partner_id
        self.channel = channel
        self.term_type = term_type
        self.opened = opened
        self.register_qty = qty
        self.status = "active"
        self.status_date = opened
        self.cancel_month = None


def simulate(rng: random.Random) -> dict:
    # --- customers --------------------------------------------------------------
    n_partner = N_CUSTOMERS - N_DIRECT
    partner_counts = {}
    remaining = n_partner
    for i, (pid, _name, share) in enumerate(PARTNERS):
        n = remaining if i == len(PARTNERS) - 1 else int(round(n_partner * share))
        partner_counts[pid] = n
        remaining -= n
    assignment = []
    for pid, _n, _s in PARTNERS:
        assignment += [pid] * partner_counts[pid]
    assignment += [DIRECT_ID] * N_DIRECT
    rng.shuffle(assignment)           # so customer_key does not encode the partner

    customers, ref_counter = [], {pid: 0 for pid, _n, _s in PARTNERS}
    ref_counter[DIRECT_ID] = 0
    for i, pid in enumerate(assignment, start=1):
        ref_counter[pid] += 1
        customers.append({
            "customer_key": f"C{i:05d}",
            "partner_id": pid,
            # Partner-scoped, zero-padded, and deliberately NOT unique across
            # partners: ref 00001 exists under every partner and under Direct.
            "customer_ref": f"{ref_counter[pid]:05d}",
            "channel": "direct" if pid == DIRECT_ID else "partner",
        })

    # --- subscriptions ------------------------------------------------------------
    subs: list[Sub] = []
    events: list[dict] = []           # raw transactions, generation order
    intended_rejects: dict[str, int] = {}
    seq = 0

    def emit(received: date, key: str, ttype: str, qty: int, term_type: str, source: str):
        nonlocal seq
        seq += 1
        events.append({
            "_seq": seq, "received_date": received, "subscription_key": key,
            "transaction_type": ttype, "requested_quantity": qty,
            "term_type": term_type, "source": source,
        })

    def open_subscription(cust: dict, opened: date) -> Sub:
        term_type = "annual" if rng.random() < P_ANNUAL else "monthly"
        if cust["channel"] == "direct":
            qty = lognormal_int(rng, DIRECT_QTY_MEDIAN, DIRECT_QTY_SIGMA, *DIRECT_QTY_RANGE)
        else:
            qty = lognormal_int(rng, PARTNER_QTY_MEDIAN, PARTNER_QTY_SIGMA, *PARTNER_QTY_RANGE)
        sub = Sub(f"S{len(subs) + 1:05d}", cust["customer_key"], cust["partner_id"],
                  cust["channel"], term_type, opened, qty)
        subs.append(sub)
        emit(opened, sub.key, "NEW", qty, term_type, source_of(sub))
        return sub

    def source_of(sub: Sub) -> str:
        return "contract_record" if sub.channel == "direct" else "partner_api_order"

    for cust in customers:
        opened = random_day(rng, WINDOW_START, WINDOW_END)
        open_subscription(cust, opened)
        if rng.random() < P_SECOND_SUBSCRIPTION:
            earliest = opened + timedelta(days=30)
            if earliest <= WINDOW_END:
                open_subscription(cust, random_day(rng, earliest, WINDOW_END))

    # --- monthly movement ----------------------------------------------------------
    active_sub_months = 0
    for m0 in months_in_window():
        m1 = min(month_end(m0), WINDOW_END)
        for sub in subs:
            if sub.opened > m1:
                continue
            first_day = max(m0, sub.opened + timedelta(days=1))
            if first_day > m1:
                continue                          # opened on the month's last day

            if sub.status == "cancelled":
                months_since = (m0.year - sub.cancel_month.year) * 12 + (m0.month - sub.cancel_month.month)
                if 0 <= months_since <= AFTER_CANCEL_MONTHS and rng.random() < P_REJECT:
                    reason = weighted_choice(rng, REJECT_MIX_CANCELLED)
                    d = random_day(rng, max(first_day, sub.status_date + timedelta(days=1)), m1) \
                        if sub.status_date < m1 else None
                    if d is None:
                        continue
                    if reason == "ADD_AFTER_CANCEL":
                        emit(d, sub.key, "ADD", max(2, sub.register_qty + 1) if sub.register_qty else 5, "", source_of(sub))
                    elif reason == "REDUCE_AFTER_CANCEL":
                        emit(d, sub.key, "REDUCE", 1, "", source_of(sub))
                    else:
                        emit(d, sub.key, "CANCEL", 0, "", source_of(sub))
                    intended_rejects[reason] = intended_rejects.get(reason, 0) + 1
                continue

            active_sub_months += 1
            r = rng.random()
            d = random_day(rng, first_day, m1)
            R = sub.register_qty
            if r < P_ADD:
                q = max(R + 1, int(round(R * rng.uniform(*ADD_UPLIFT))))
                emit(d, sub.key, "ADD", q, "", source_of(sub))
                sub.register_qty = q
            elif r < P_ADD + P_REDUCE:
                if R > 1:
                    q = min(R - 1, max(1, int(math.floor(R * rng.uniform(*REDUCE_FACTOR)))))
                    emit(d, sub.key, "REDUCE", q, "", source_of(sub))
                    sub.register_qty = q
            elif r < P_ADD + P_REDUCE + P_CANCEL:
                emit(d, sub.key, "CANCEL", 0, "", source_of(sub))
                sub.register_qty = 0
                sub.status = "cancelled"
                sub.status_date = d
                sub.cancel_month = m0
            elif r < P_ADD + P_REDUCE + P_CANCEL + P_REJECT:
                reason = weighted_choice(rng, REJECT_MIX_ACTIVE)
                if reason == "NOOP_QUANTITY":
                    emit(d, sub.key, "ADD", R, "", source_of(sub))
                elif reason == "REDUCE_TO_ZERO":
                    emit(d, sub.key, "REDUCE", 0, "", source_of(sub))
                elif reason == "DUPLICATE_NEW":
                    emit(d, sub.key, "NEW", max(1, R), sub.term_type, source_of(sub))
                else:
                    unknown = f"S{UNKNOWN_KEY_BASE + rng.randint(1, 999):05d}"
                    emit(d, unknown, "ADD" if rng.random() < 0.5 else "REDUCE",
                         rng.randint(1, 20), "", "partner_api_order")
                intended_rejects[reason] = intended_rejects.get(reason, 0) + 1
            # else: flat

    # --- assign monotonic transaction ids -------------------------------------------
    events.sort(key=lambda e: (e["received_date"], e["_seq"]))
    for i, e in enumerate(events, start=1):
        e["transaction_id"] = i

    return {
        "customers": customers,
        "subs": subs,
        "events": events,
        "partner_counts": partner_counts,
        "active_sub_months": active_sub_months,
        "intended_rejects": dict(sorted(intended_rejects.items())),
    }


