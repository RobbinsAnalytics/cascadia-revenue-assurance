"""generate.py -- seeded synthetic generator for Cascadia Revenue Assurance.

    ALL DATA IN THIS REPOSITORY IS SYNTHETIC. It is generated by this file
    from a fixed seed. There is no real company, customer, partner, product
    or person anywhere in it, and there never will be. Every figure the
    module publishes traces back to the parameter block below.

What this file does
    Simulates what customers ASK FOR -- it emits order transactions. It does
    not, anywhere, compute what a customer is billable for. Effective
    quantities, term boundaries, accepted/rejected flags and every derived
    row are the engines' to produce from the event stream and the rules in
    governance/entitlement-rules.md. The generator knows only the register:
    the last quantity each customer requested, and whether they cancelled.

Outputs (data/raw/ is the frozen snapshot; see governance/freeze.toml)
    data/raw/customers.csv                one row per customer
    data/raw/subscriptions_register.csv   one row per subscription, register
                                          attributes as of the as-of date
    data/raw/order_events.csv             one row per transaction received
    data/raw/manifest.json                seed, window, parameters, counts
    governance/generator_assumptions.md   the disclosure, the parameter block,
                                          the realised mix beside the design

Determinism
    One random.Random(SEED). Customers, months and subscriptions are iterated
    in fixed order; no set iteration anywhere. transaction_id is assigned
    AFTER sorting every transaction by (received_date, generation order), so
    it is monotonic in date -- D9 depends on that. The same seed reproduces
    byte-identical files, and src/validate.py proves it by regenerating into
    a temporary folder and diffing.

Usage
    python src/generate.py
"""

from __future__ import annotations

import calendar
import csv
import json
import math
import random
import sys
from datetime import date, timedelta
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

REPO_ROOT = Path(__file__).resolve().parent.parent
RAW_DIR = REPO_ROOT / "data" / "raw"
ASSUMPTIONS_PATH = REPO_ROOT / "governance" / "generator_assumptions.md"

GENERATOR_VERSION = "1.0.0"

# ===========================================================================
# PARAMETER BLOCK -- every tunable assumption, in one place (D11).
# ===========================================================================

SEED = 20260911                       # fixed seed; same seed => byte-identical files
AS_OF = date(2026, 6, 30)             # the "today" the register describes
WINDOW_START = date(2024, 7, 1)       # first possible opening date
WINDOW_END = date(2026, 6, 30)        # last possible transaction date (24 months)

DISCLOSURE = ("Synthetic data from a seeded generator (seed %d). Simulated: "
              "not a real company, customer, partner, product or book of business."
              % SEED)

# --- population --------------------------------------------------------------
N_CUSTOMERS = 4_000
N_DIRECT = 200                        # the rest are Partner
PARTNERS = [                          # partner_id, invented name, share of Partner customers
    ("P1", "Ochre Basalt Partners", 0.55),
    ("P2", "Teal Gypsum Channel", 0.30),
    ("P3", "Umber Quartz Resale", 0.15),
]
DIRECT_ID = "DIRECT"
DIRECT_NAME = "Direct (no partner)"

P_ANNUAL = 0.60                       # term mix; the rest monthly
P_SECOND_SUBSCRIPTION = 0.10          # customers who open a second subscription later

# --- licence counts (log-normal, then clamped) ---------------------------------
PARTNER_QTY_MEDIAN, PARTNER_QTY_SIGMA, PARTNER_QTY_RANGE = 8, 0.90, (1, 80)
DIRECT_QTY_MEDIAN, DIRECT_QTY_SIGMA, DIRECT_QTY_RANGE = 200, 0.70, (25, 2_000)

# --- monthly movement, per active subscription-month (D11) ---------------------
P_ADD = 0.030
P_REDUCE = 0.020
P_CANCEL = 0.010
P_REJECT = 0.005                      # a transaction the rules will refuse
ADD_UPLIFT = (1.10, 1.60)             # multiplier on the register quantity, min +1
REDUCE_FACTOR = (0.40, 0.90)          # multiplier on the register quantity, min 1

# The kind of refused transaction, when one is rolled. Two mixes, because the
# after-cancel reasons need a cancelled subscription to exist.
REJECT_MIX_ACTIVE = [                 # on a subscription that is still active
    ("NOOP_QUANTITY", 0.45),
    ("REDUCE_TO_ZERO", 0.25),
    ("DUPLICATE_NEW", 0.15),
    ("UNKNOWN_SUBSCRIPTION", 0.15),
]
REJECT_MIX_CANCELLED = [              # on a subscription cancelled recently
    ("ADD_AFTER_CANCEL", 0.40),
    ("REDUCE_AFTER_CANCEL", 0.40),
    ("DUPLICATE_CANCEL", 0.20),
]
AFTER_CANCEL_MONTHS = 3               # how long a cancelled key keeps attracting rejects

UNKNOWN_KEY_BASE = 90_000             # subscription numbers never issued

# ===========================================================================
# helpers
# ===========================================================================


def month_end(d: date) -> date:
    return date(d.year, d.month, calendar.monthrange(d.year, d.month)[1])


def months_in_window() -> list[date]:
    """First day of every month from WINDOW_START through WINDOW_END."""
    out, d = [], date(WINDOW_START.year, WINDOW_START.month, 1)
    while d <= WINDOW_END:
        out.append(d)
        d = date(d.year + (d.month == 12), d.month % 12 + 1, 1)
    return out


def weighted_choice(rng: random.Random, pairs: list[tuple[str, float]]) -> str:
    r, acc = rng.random(), 0.0
    for name, w in pairs:
        acc += w
        if r < acc:
            return name
    return pairs[-1][0]


def lognormal_int(rng: random.Random, median: float, sigma: float, lo: int, hi: int) -> int:
    v = int(round(math.exp(rng.gauss(math.log(median), sigma))))
    return max(lo, min(hi, v))


def random_day(rng: random.Random, first: date, last: date) -> date:
    return first + timedelta(days=rng.randint(0, (last - first).days))


